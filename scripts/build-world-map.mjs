// Purpose: build the "Going global" world map for the Branches section from public-domain data (Natural Earth,
// via world-atlas). Everything is VECTOR, so the map stays razor-sharp at every zoom of the camera pull-back
// (the old NASA satellite crop was a bitmap and went soft when scaled).
//   src/pages/Branches/worldShapes.generated.js —
//     • WORLD_LAND / WORLD_BORDERS / WORLD_GRATICULE: the holographic dot-matrix map (1:110m, light)
//     • COUNTRY_SHAPES: outlines of the highlighted countries (1:50m), in the same world-map units
// Run after changing WORLD or the highlighted countries:  npm run build:world-map
import { readFileSync, writeFileSync } from "node:fs";
import { feature, mesh } from "topojson-client";
import { geoEquirectangular, geoPath, geoGraticule } from "d3-geo";
import { WORLD, HIGHLIGHT_COUNTRIES, REGION } from "../src/pages/Branches/branchesData.js";

const root = (p) => new URL(`../${p}`, import.meta.url);

/* 2 · country outlines in world-map units */
const topo = JSON.parse(readFileSync(root("node_modules/world-atlas/countries-50m.json")));
const topoLight = JSON.parse(readFileSync(root("node_modules/world-atlas/countries-110m.json")));
const countries = feature(topo, topo.objects.countries).features;
const projection = geoEquirectangular()
  .scale((WORLD.k * 180) / Math.PI)
  .translate([-WORLD.lon0 * WORLD.k, WORLD.lat0 * WORLD.k])
  .clipExtent([
    [-4, -4],
    [WORLD.w + 4, WORLD.h + 4],
  ]);
const path = geoPath(projection).digits(1);
const shapes = {};
for (const [key, isoNumeric] of Object.entries(HIGHLIGHT_COUNTRIES)) {
  const f = countries.find((c) => String(c.id) === isoNumeric);
  if (!f) throw new Error(`country ${key} (${isoNumeric}) not found`);
  shapes[key] = path(f) || "";
}
/* 1 · the base map: land, internal borders and a 15° graticule */
const land = path(feature(topoLight, topoLight.objects.land)) || "";
const borders = path(mesh(topoLight, topoLight.objects.countries, (a, b) => a !== b)) || "";
const graticule = path(geoGraticule().step([15, 15])()) || "";

/* 3 · the India & Gulf close-up (chapter 1): 1:50m land, clipped to REGION, so the zoomed-in dot matrix has
   real coastline detail without making the whole-world map heavier (borders reuse the 1:110m mesh) */
const [rx0, ry0] = projection([REGION.lon0, REGION.lat0]);
const [rx1, ry1] = projection([REGION.lon1, REGION.lat1]);
const regionProj = geoEquirectangular()
  .scale((WORLD.k * 180) / Math.PI)
  .translate([-WORLD.lon0 * WORLD.k, WORLD.lat0 * WORLD.k])
  .clipExtent([
    [rx0, ry0],
    [rx1, ry1],
  ]);
const regionPath = geoPath(regionProj).digits(1);
const regionLand = regionPath(feature(topo, topo.objects.land)) || "";

writeFileSync(
  root("src/pages/Branches/worldShapes.generated.js"),
  `// GENERATED by scripts/build-world-map.mjs — do not edit by hand (run: npm run build:world-map)\n` +
    `// Country outlines (Natural Earth 1:50m) in world-map units; see WORLD in branchesData.js.\n` +
    `export const COUNTRY_SHAPES = ${JSON.stringify(shapes, null, 2)};\n` +
    `// Base map (Natural Earth 1:110m): land, country borders, 15° graticule.\n` +
    `export const WORLD_LAND = ${JSON.stringify(land)};\n` +
    `export const WORLD_BORDERS = ${JSON.stringify(borders)};\n` +
    `export const WORLD_GRATICULE = ${JSON.stringify(graticule)};\n` +
    `// India & Gulf close-up land (Natural Earth 1:50m), clipped to REGION in branchesData.js.\n` +
    `export const REGION_LAND = ${JSON.stringify(regionLand)};\n`
);
console.log(`vector world map (${(land.length / 1024).toFixed(0)} KB land) + outlines for: ${Object.keys(shapes).join(", ")}`);
